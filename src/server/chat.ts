// Who's who

/** When a transcript last changed (ms), or undefined when there isn't one yet. */
function modifiedAt(file: string | undefined): number | undefined {
  if (!file) return undefined;
  try {
    return statSync(file).mtimeMs;
  } catch {
    return undefined;
  }
}

/** A worker as the app lists it (see TeamEntry). */
export function teamEntry(info: WorkerInfo, transcript: string | undefined): TeamEntry {
  const e: TeamEntry = { id: info.id, name: info.name, color: info.color, status: info.status, acked: info.acked, kind: info.kind };
  const member = info.role ? TEAM_BY_ID.get(info.role) : undefined;
  if (info.role) e.role = info.role;
  if (member) e.emoji = member.emoji;
  if (info.waitingSince !== undefined) e.waitingSince = info.waitingSince;
  if (info.activity) e.activity = info.activity;
  if (info.title) e.title = info.title;
  if (info.parked) e.parked = true;
  if (info.meeting) e.meeting = info.meeting;
  const at = modifiedAt(transcript);
  if (at !== undefined) e.lastMessageAt = at;
  return e;
}

/** What /api/team needs of a floor: its name and its workers. */
export interface TeamFloor {
  id: string;
  def: { name: string };
  workers: { list(): WorkerInfo[]; transcriptOf(id: string): string | undefined };
}

/** GET /api/team: every floor's workers. Empty kiosk seats have no worker, so they never show. */
export function teamOf(floors: Iterable<TeamFloor>): TeamResponse {
  return {
    floors: [...floors].map((f) => ({ id: f.id, name: f.def.name, workers: f.workers.list().map((w) => teamEntry(w, f.workers.transcriptOf(w.id))) })),
  };
}

/** GET /api/chat: who the worker is and what's been said. */
export function workerChat(info: WorkerInfo, transcript: string | undefined): ChatResponse {
  return { worker: teamEntry(info, transcript), messages: readChat(transcript) };
}

/** Forgets every cached parse (tests). */
export function clearChatCache() {
  cache.clear();
}
